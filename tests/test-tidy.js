const {launch,makeDisk,btn,settle,suite}=require('./sandbox');
const T=suite();
(async()=>{
  const a=launch(makeDisk()); await settle(250);
  a.ev("state.standard={all:['Bed','TV','Desk x2'],byType:{}}; state.stdSeeded=true; state.rooms=[]; addRooms('114','Economy Single')");
  const rid=a.state.rooms[0].id;
  a.ev(`room('${rid}').work.push({id:'j1',task:'Fix fan',priority:'Normal',status:'notdone',notes:'',assignee:'Handyman'})`);
  a.ev(`showRoom('${rid}')`); await settle(200);
  const html=a.els.roomView.innerHTML;
  const todoCard=html.slice(html.indexOf('id="sec-todo"'),html.indexOf('id="sec-photos"'));
  T.section('missing items appear once');
  T.ok(!/data-stdpresent/.test(todoCard),'the room to-do card has no Here/Missing buttons');
  T.ok(/3 items missing or short from the room standard/.test(todoCard),'just one summary line pointing down');
  T.ok(/data-jump="sec-std"/.test(todoCard),'with a button that jumps to the Standard section');
  T.ok(/Fix fan/.test(todoCard),'jobs still show in the to-do card');
  T.ok((html.match(/data-stdpresent="Bed"/g)||[]).length===1,'Bed has exactly one Here button on the whole screen');
  T.ok(/Standard · 3 missing/.test(html),'the jump bar shows the count');
  T.section('the combined To-do list still lists each gap');
  a.ev('todoTab="room"; showTodo()'); await settle();
  T.ok(/data-stdpresent="Bed"/.test(a.els.todoView.innerHTML),'the all-rooms list keeps per-item buttons');
  T.section('one job preset list');
  a.ev(`showRoom('${rid}')`); await settle();
  T.ok(!/Common jobs/.test(a.els.roomView.innerHTML),'the old Common jobs button is gone');
  a.ev('sheetWork(null)');
  T.ok(/<option>Deep clean<\/option>/.test(a.els.sheetBody.innerHTML)&&/<option>Leak or plumbing<\/option>/.test(a.els.sheetBody.innerHTML),'one dropdown covers both');
  T.section('slim save status');
  a.ev('renderSaveBar()');
  T.ok(!a.sb.document.getElementById('saveRoom').innerHTML&&/All changes saved|Saving/.test(a.els.saveMsg.innerHTML),'a status line, no Save button');
  T.section('sync dot');
  a.ev("syncState.err=''; syncState.last=Date.now(); syncState.busy=false; renderSyncChip()");
  T.ok(/s-ok/.test(a.els.syncBtn.className),'green when synced');
  a.ev("syncState.err='offline'; renderSyncChip()");
  T.ok(/s-off/.test(a.els.syncBtn.className)&&/Offline/.test(a.els.syncBtn.title),'hollow when offline, with a label');
  T.done();
})();
