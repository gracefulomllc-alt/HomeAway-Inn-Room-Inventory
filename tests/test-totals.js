const {launch,makeDisk,settle,suite}=require('./sandbox');
const T=suite();
(async()=>{
  const a=launch(makeDisk()); await settle(250);
  a.ev("state.standard={all:['TV','Informational folder','Working AC','Desk x2'],byType:{}}; state.stdSeeded=true; state.rooms=[]; addRooms('101,102,103,104,105','Economy Single');");
  a.ev(`(()=>{ const R=state.rooms, put=(r,n,q,c)=>r.inventory.push({id:n+r.number,name:n,qty:q,condition:c,notes:''});
    put(R[0],'TV',1,'Good'); put(R[0],'Informational folder',1,'Good'); put(R[0],'Working AC',1,'Good'); put(R[0],'Desk',2,'Good');
    put(R[1],'TV',1,'Good'); put(R[1],'Working AC',1,'Poor'); put(R[1],'Desk',1,'Good');
    put(R[2],'TV',1,'Damaged'); put(R[2],'Working AC',1,'Fair');
    put(R[3],'Working AC',1,'Good'); put(R[3],'Desk',2,'Fair');
    put(R[4],'TV',1,'Missing'); put(R[4],'Working AC',1,'Good'); put(R[4],'Desk',2,'Good'); put(R[4],'Informational folder',1,'Good'); })()`);
  const t=a.ev('inventoryTotals(state.rooms)');
  const f=n=>t.find(e=>e.name===n);
  T.section('TVs');
  T.ok(f('TV').units===3,'three TVs on hand — 104 has none, 105 is marked Missing');
  T.ok(f('TV').shortUnits===2,'two TVs to buy');
  T.ok(f('TV').missingRooms.join()==='104,105','missing in rooms 104 and 105');
  T.ok(f('TV').working===2&&f('TV').attention===1,'two working, one damaged');
  T.section('how many ACs work');
  T.ok(f('Working AC').units===5,'five AC units on hand');
  T.ok(f('Working AC').working===4,'four working (three good, one fair)');
  T.ok(f('Working AC').attention===1,'one needs attention');
  T.section('quantities above one');
  T.ok(f('Desk').required===10&&f('Desk').units===7&&f('Desk').shortUnits===3,'ten desks needed, seven on hand, three to buy');
  T.section('informational folders');
  T.ok(f('Informational folder').units===2&&f('Informational folder').shortUnits===3,'two folders on hand, three to buy');
  T.section('rendering');
  const html=a.ev('renderTotals()');
  T.ok(/to buy/.test(html)&&/to fix/.test(html)&&/Working AC/.test(html),'By item tab renders the totals');
  T.done();
})();
